/**
 * Encodes an AudioBuffer into a 16 kHz mono 16-bit PCM WAV Blob (matching QVAC Whisper requirements).
 */
async function blobTo16kHzMonoWav(audioBlob) {
  const arrayBuffer = await audioBlob.arrayBuffer();
  const AudioCtx = window.AudioContext || window.webkitAudioContext;
  const audioCtx = new AudioCtx();
  const decoded = await audioCtx.decodeAudioData(arrayBuffer);

  const targetSampleRate = 16000;
  const offlineCtx = new OfflineAudioContext(
    1,
    Math.ceil(decoded.duration * targetSampleRate),
    targetSampleRate,
  );

  const source = offlineCtx.createBufferSource();
  source.buffer = decoded;
  source.connect(offlineCtx.destination);
  source.start(0);

  const rendered = await offlineCtx.startRendering();
  const pcmData = rendered.getChannelData(0);

  const wavBuffer = new ArrayBuffer(44 + pcmData.length * 2);
  const view = new DataView(wavBuffer);

  const writeString = (offset, str) => {
    for (let i = 0; i < str.length; i++) {
      view.setUint8(offset + i, str.charCodeAt(i));
    }
  };

  writeString(0, "RIFF");
  view.setUint32(4, 36 + pcmData.length * 2, true);
  writeString(8, "WAVE");
  writeString(12, "fmt ");
  view.setUint32(16, 16, true); // Subchunk1Size (PCM)
  view.setUint16(20, 1, true); // AudioFormat (1 = PCM)
  view.setUint16(22, 1, true); // NumChannels (1 = mono)
  view.setUint32(24, targetSampleRate, true);
  view.setUint32(28, targetSampleRate * 2, true); // ByteRate
  view.setUint16(32, 2, true); // BlockAlign
  view.setUint16(34, 16, true); // BitsPerSample
  writeString(36, "data");
  view.setUint32(40, pcmData.length * 2, true);

  let offset = 44;
  for (let i = 0; i < pcmData.length; i++, offset += 2) {
    const sample = Math.max(-1, Math.min(1, pcmData[i]));
    view.setInt16(offset, sample < 0 ? sample * 0x8000 : sample * 0x7fff, true);
  }

  await audioCtx.close();
  return new Blob([wavBuffer], { type: "audio/wav" });
}

/**
 * Mounts the Hiker A Push-to-Talk + Typed-Fallback report submission component.
 */
export function createRecordReport(
  container,
  { transcribeRecording, submitTranscript, onSubmitted } = {},
) {
  let mediaRecorder = null;
  let recordedChunks = [];
  let isRecording = false;

  container.innerHTML = `
    <section class="ts-card">
      <div class="ts-card-header">
        <div>
          <h2>Device A — Hiker Report</h2>
          <p class="ts-subtitle">Record spoken report (QVAC STT) or use typed-text fallback</p>
        </div>
        <span class="ts-badge ts-badge-offline">Local QVAC STT</span>
      </div>

      <div class="ts-ptt-box">
        <button type="button" id="ts-ptt-btn" class="ts-btn ts-btn-ptt">
          🎤 Start Push-to-Talk Recording
        </button>
        <span id="ts-ptt-status" class="ts-ptt-status">Ready to record (16 kHz mono WAV)</span>
      </div>

      <form id="ts-report-form" class="ts-form">
        <label class="ts-label" for="ts-raw-transcript">
          Raw Transcript (Generated by QVAC STT or typed manually as fallback)
        </label>
        <textarea
          id="ts-raw-transcript"
          class="ts-textarea"
          rows="4"
          placeholder="e.g. A landslide is blocking the path between Bridge 2 and the summit."
          required
        ></textarea>

        <button type="submit" id="ts-send-btn" class="ts-btn ts-btn-primary">
          Send Transcript to Checkpoint (Pear P2P)
        </button>

        <div id="ts-form-feedback" class="ts-feedback" hidden></div>
        <div id="ts-receipt-box" class="ts-receipt" hidden></div>
      </form>
    </section>
  `;

  const pttBtn = container.querySelector("#ts-ptt-btn");
  const pttStatusEl = container.querySelector("#ts-ptt-status");
  const formEl = container.querySelector("#ts-report-form");
  const transcriptEl = container.querySelector("#ts-raw-transcript");
  const sendBtn = container.querySelector("#ts-send-btn");
  const feedbackEl = container.querySelector("#ts-form-feedback");
  const receiptEl = container.querySelector("#ts-receipt-box");

  function setFeedback(message, isError = false) {
    feedbackEl.hidden = !message;
    feedbackEl.textContent = message;
    feedbackEl.className = `ts-feedback ${isError ? "ts-feedback-error" : "ts-feedback-ok"}`;
  }

  function showReceipt(reportId, createdAt) {
    receiptEl.hidden = false;
    receiptEl.innerHTML = `
      <strong>✓ Checkpoint Acknowledged Receipt (REPORT_RECEIVED)</strong>
      <div>Report ID: <code>${reportId}</code></div>
      <div>Sent at: ${new Date(createdAt).toLocaleTimeString()}</div>
    `;
  }

  async function runTranscription(wavBlob = null) {
    pttBtn.disabled = true;
    pttStatusEl.textContent = "Running local QVAC speech-to-text...";
    setFeedback("Transcribing audio locally with QVAC...");

    try {
      if (typeof transcribeRecording !== "function") {
        throw new Error(
          "transcribeRecording function not provided; please use typed-text fallback.",
        );
      }

      // Pass wavBlob (for browser capture) or null (if Person 3's function captures via native CLI)
      const transcript = await transcribeRecording(wavBlob);
      if (transcript && typeof transcript === "string") {
        transcriptEl.value = transcript.trim();
        pttStatusEl.textContent = "Transcription complete";
        setFeedback(
          "QVAC transcription complete. Review or send to checkpoint.",
        );
      } else {
        throw new Error("Empty transcript returned by model.");
      }
    } catch (err) {
      pttStatusEl.textContent = "STT unavailable — use typed fallback below";
      setFeedback(
        `Audio transcription fallback triggered: ${err.message}`,
        true,
      );
    } finally {
      pttBtn.disabled = false;
    }
  }

  pttBtn.addEventListener("click", async () => {
    receiptEl.hidden = true;

    // Stop recording if already active
    if (isRecording && mediaRecorder) {
      mediaRecorder.stop();
      return;
    }

    // Dual-mode: try browser MediaRecorder first; if unavailable/denied, delegate directly to native transcribeRecording()
    if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) {
      await runTranscription(null);
      return;
    }

    try {
      const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
      recordedChunks = [];
      mediaRecorder = new MediaRecorder(stream);

      mediaRecorder.ondataavailable = (e) => {
        if (e.data && e.data.size > 0) recordedChunks.push(e.data);
      };

      mediaRecorder.onstop = async () => {
        isRecording = false;
        pttBtn.classList.remove("ts-recording");
        pttBtn.textContent = "🎤 Start Push-to-Talk Recording";
        stream.getTracks().forEach((track) => track.stop());

        try {
          const rawBlob = new Blob(recordedChunks, {
            type: mediaRecorder.mimeType || "audio/webm",
          });
          const wavBlob = await blobTo16kHzMonoWav(rawBlob);
          await runTranscription(wavBlob);
        } catch (_) {
          // If browser WAV conversion fails, pass raw blob or trigger native hook
          await runTranscription(null);
        }
      };

      mediaRecorder.start();
      isRecording = true;
      pttBtn.classList.add("ts-recording");
      pttBtn.textContent = "⏹ Stop Recording & Transcribe";
      pttStatusEl.textContent = "Recording voice report... click again to stop";
    } catch (_) {
      // Microphone permission denied or handled natively by Bare/Node
      await runTranscription(null);
    }
  });

  formEl.addEventListener("submit", async (e) => {
    e.preventDefault();
    const rawTranscript = transcriptEl.value.trim();
    if (!rawTranscript) return;

    sendBtn.disabled = true;
    transcriptEl.disabled = true;
    receiptEl.hidden = true;
    sendBtn.textContent = "Sending to Checkpoint...";
    setFeedback("Sending SUBMIT_REPORT over Pear P2P...");

    const payload = {
      type: "SUBMIT_REPORT",
      reportId: `rep-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
      createdAt: new Date().toISOString(),
      rawTranscript,
    };

    try {
      let ack = null;
      if (typeof submitTranscript === "function") {
        ack = await submitTranscript(payload);
      }

      const confirmedId = (ack && ack.reportId) || payload.reportId;
      setFeedback("Transcript delivered to checkpoint.");
      showReceipt(confirmedId, payload.createdAt);
      transcriptEl.value = "";

      if (typeof onSubmitted === "function") {
        onSubmitted({ ...payload, reportId: confirmedId });
      }
    } catch (err) {
      setFeedback(`Failed to send transcript: ${err.message}`, true);
    } finally {
      sendBtn.disabled = false;
      transcriptEl.disabled = false;
      sendBtn.textContent = "Send Transcript to Checkpoint (Pear P2P)";
    }
  });
}
